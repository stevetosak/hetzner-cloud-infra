#!/usr/bin/env bash
# Renders core/monitoring/kube-prometheus-stack.yaml and core/monitoring/crds.yaml
# from the pinned upstream chart.
#
# Run from anywhere:  ./core/monitoring/render.sh
#
# The chart is pulled to a temporary directory before rendering, as in
# core/cert-manager/render.sh: `helm template` against an oci:// chart prints
# "Pulled:" and "Digest:" on STDOUT on a cold cache and would corrupt the file.
set -euo pipefail

CHART="oci://ghcr.io/prometheus-community/charts/kube-prometheus-stack"
VERSION="92.17.0"
NAMESPACE="monitoring"
RELEASE="kps"
# The cluster's version. Without it, helm renders for its own built-in
# version, and the chart's version gates pick the wrong API fields.
KUBE_VERSION="1.37.0"

cd "$(dirname "$0")/../.."
OUT="core/monitoring/kube-prometheus-stack.yaml"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

DIGEST="$(helm pull "$CHART" --version "$VERSION" --untar --untardir "$TMP" \
  | awk '/^Digest:/ {print $2}')"
[ -n "$DIGEST" ] || { echo "helm pull printed no digest" >&2; exit 1; }

# --skip-tests: the chart's test pods are helm hooks, nothing ArgoCD should run.
helm template "$RELEASE" "$TMP/kube-prometheus-stack" \
  --namespace "$NAMESPACE" \
  --kube-version "$KUBE_VERSION" \
  --include-crds \
  --skip-tests \
  --values core/monitoring/kube-prometheus-stack-values.yaml \
  > "$TMP/rendered.yaml"

# A value that changes on every render would keep the sync from settling.
if grep -n -E 'helm\.sh/hook|randAlphaNum|genCA' "$TMP/rendered.yaml"; then
  echo "the render holds a helm hook or a random value; check the values" >&2
  exit 1
fi

# CRDs go to their own file: only kluster applies them (ADR 0010, Amendment
# 2026-10-22), and no kustomize build may contain one.
python3 core/split-crds.py "$TMP/crds.yaml" < "$TMP/rendered.yaml" > "$TMP/rest.yaml"

{
  echo "# kube-prometheus-stack ${VERSION}, rendered from ${CHART}"
  echo "# ${DIGEST}"
  echo "#"
  echo "# Generated by core/monitoring/render.sh. Do NOT edit in place —"
  echo "# change core/monitoring/kube-prometheus-stack-values.yaml and render again."
  cat "$TMP/rest.yaml"
} > "$OUT"

{
  echo "# CustomResourceDefinitions split from the same render as kube-prometheus-stack.yaml."
  echo "# Generated by core/monitoring/render.sh. Do NOT edit in place."
  echo "#"
  echo "# Applied by the kluster seed with --server-side, never by ArgoCD: the core"
  echo "# AppProject does not admit CRDs, and the Prometheus CRD is over the size"
  echo "# limit of a client-side apply. Not listed in kustomization.yaml."
  cat "$TMP/crds.yaml"
} > "core/monitoring/crds.yaml"

echo "wrote $OUT and core/monitoring/crds.yaml"
