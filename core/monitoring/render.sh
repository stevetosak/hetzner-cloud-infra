#!/usr/bin/env bash
# Renders the pinned upstream charts of core/monitoring:
#
#   kube-prometheus-stack.yaml + crds.yaml   kube-prometheus-stack
#   blackbox-exporter.yaml                   prometheus-blackbox-exporter
#
# Run from anywhere:  ./core/monitoring/render.sh
#
# Each chart is pulled to a temporary directory before rendering, as in
# core/cert-manager/render.sh: `helm template` against an oci:// chart prints
# "Pulled:" and "Digest:" on STDOUT on a cold cache and would corrupt the file.
set -euo pipefail

REPO="oci://ghcr.io/prometheus-community/charts"
NAMESPACE="monitoring"
# The cluster's version. Without it, helm renders for its own built-in
# version, and the chart's version gates pick the wrong API fields.
KUBE_VERSION="1.37.0"

cd "$(dirname "$0")/../.."
DIR="core/monitoring"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# template <chart> <release> <values file>
# Renders the pulled chart in $TMP to STDOUT.
template() {
  local chart="$1" release="$2" values="$3"
  # --skip-tests: the chart's test pods are helm hooks, nothing ArgoCD should run.
  helm template "$release" "$TMP/$chart" \
    --namespace "$NAMESPACE" \
    --kube-version "$KUBE_VERSION" \
    --include-crds \
    --skip-tests \
    --values "$values"
}

# render <chart> <version> <release> <values file>
# Pulls the chart and renders it with its CRDs into $TMP/<chart>.yaml, and
# writes $TMP/<chart>.header, which names the chart, its version and its
# digest. The header stays apart: split-crds.py drops a leading comment.
render() {
  local chart="$1" version="$2" release="$3" values="$4"
  local digest
  digest="$(helm pull "$REPO/$chart" --version "$version" --untar --untardir "$TMP" \
    | awk '/^Digest:/ {print $2}')"
  [ -n "$digest" ] || { echo "$chart: helm pull printed no digest" >&2; exit 1; }

  template "$chart" "$release" "$values" > "$TMP/$chart.yaml"

  # ArgoCD does not run helm hooks; a hook in the render would never run.
  if grep -n -E 'helm\.sh/hook' "$TMP/$chart.yaml"; then
    echo "$chart: the render holds a helm hook; check the values" >&2
    exit 1
  fi

  # A value that changes on every render (randAlphaNum, genCA, uuidv4, now)
  # would keep the sync from settling. Those functions leave no name in the
  # output, so a grep cannot find them: render again and compare.
  template "$chart" "$release" "$values" > "$TMP/$chart.again.yaml"
  if ! diff -u "$TMP/$chart.yaml" "$TMP/$chart.again.yaml" >&2; then
    echo "$chart: two renders differ, the chart renders a value that changes; check the values" >&2
    exit 1
  fi

  {
    echo "# $chart ${version}, rendered from $REPO/$chart"
    echo "# ${digest}"
    echo "#"
    echo "# Generated by core/monitoring/render.sh. Do NOT edit in place —"
    echo "# change $values and render again."
  } > "$TMP/$chart.header"
}

render kube-prometheus-stack 92.17.0 kps "$DIR/kube-prometheus-stack-values.yaml"

# CRDs go to their own file: only kluster applies them (ADR 0010, Amendment
# 2026-10-22), and no kustomize build may contain one.
python3 core/split-crds.py "$TMP/crds.yaml" < "$TMP/kube-prometheus-stack.yaml" > "$TMP/rest.yaml"
cat "$TMP/kube-prometheus-stack.header" "$TMP/rest.yaml" > "$DIR/kube-prometheus-stack.yaml"
{
  echo "# CustomResourceDefinitions split from the same render as kube-prometheus-stack.yaml."
  echo "# Generated by core/monitoring/render.sh. Do NOT edit in place."
  echo "#"
  echo "# Applied by the kluster seed with --server-side, never by ArgoCD: the core"
  echo "# AppProject does not admit CRDs, and the Prometheus CRD is over the size"
  echo "# limit of a client-side apply. Not listed in kustomization.yaml."
  cat "$TMP/crds.yaml"
} > "$DIR/crds.yaml"

# The prober of the public hosts (ADR 0011); probes/ names its Service.
render prometheus-blackbox-exporter 11.20.2 blackbox "$DIR/blackbox-exporter-values.yaml"
if grep -q '^kind: CustomResourceDefinition' "$TMP/prometheus-blackbox-exporter.yaml"; then
  echo "the blackbox-exporter render holds a CRD; split it as for kube-prometheus-stack" >&2
  exit 1
fi
cat "$TMP/prometheus-blackbox-exporter.header" "$TMP/prometheus-blackbox-exporter.yaml" \
  > "$DIR/blackbox-exporter.yaml"

echo "wrote $DIR/kube-prometheus-stack.yaml, $DIR/crds.yaml and $DIR/blackbox-exporter.yaml"
