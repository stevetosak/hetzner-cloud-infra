#!/usr/bin/env bash
# Renders core/vpa/vertical-pod-autoscaler.yaml from the pinned upstream chart.
#
# Run from anywhere:  ./core/vpa/render.sh
#
# The chart comes from a classic helm repository, which prints no digest, so
# the header records the sha256 of the pulled chart archive instead.
set -euo pipefail

REPO="https://kubernetes.github.io/autoscaler"
CHART="vertical-pod-autoscaler"
VERSION="0.15.0"
NAMESPACE="vpa"
RELEASE="vpa"
KUBE_VERSION="1.37.0"

cd "$(dirname "$0")/../.."
DIR="core/vpa"
OUT="$DIR/vertical-pod-autoscaler.yaml"
VALUES="$DIR/vpa-values.yaml"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

helm pull "$CHART" --repo "$REPO" --version "$VERSION" --destination "$TMP" >/dev/null
ARCHIVE="$TMP/$CHART-$VERSION.tgz"
DIGEST="sha256:$(sha256sum "$ARCHIVE" | cut -d' ' -f1)"
tar -xzf "$ARCHIVE" -C "$TMP"

template() {
  helm template "$RELEASE" "$TMP/$CHART" \
    --namespace "$NAMESPACE" \
    --kube-version "$KUBE_VERSION" \
    --skip-tests \
    --values "$VALUES"
}

template > "$TMP/rendered.yaml"

# ArgoCD does not run helm hooks; a hook in the render would never run.
if grep -n -E 'helm\.sh/hook' "$TMP/rendered.yaml"; then
  echo "the render holds a helm hook; check the values" >&2
  exit 1
fi

# A value that changes on every render would keep the sync from settling.
template > "$TMP/again.yaml"
if ! diff -u "$TMP/rendered.yaml" "$TMP/again.yaml" >&2; then
  echo "two renders differ, the chart renders a value that changes; check the values" >&2
  exit 1
fi

# CRDs go to their own file: only kluster applies them (ADR 0010, Amendment
# 2026-10-22), and no kustomize build may contain one. The chart renders its
# CRDs from templates/, so they are in the render without --include-crds.
python3 core/split-crds.py "$TMP/crds.yaml" < "$TMP/rendered.yaml" > "$TMP/rest.yaml"

{
  echo "# Vertical Pod Autoscaler chart ${VERSION}, rendered from ${REPO}"
  echo "# chart archive ${DIGEST}"
  echo "#"
  echo "# Generated by core/vpa/render.sh. Do NOT edit in place —"
  echo "# change core/vpa/vpa-values.yaml and render again."
  cat "$TMP/rest.yaml"
} > "$OUT"

{
  echo "# CustomResourceDefinitions split from the same render as vertical-pod-autoscaler.yaml."
  echo "# Generated by core/vpa/render.sh. Do NOT edit in place."
  echo "#"
  echo "# Applied by the kluster seed with --server-side, never by ArgoCD: the core"
  echo "# AppProject does not admit CRDs. Not listed in kustomization.yaml."
  cat "$TMP/crds.yaml"
} > "$DIR/crds.yaml"

echo "wrote $OUT and $DIR/crds.yaml"
