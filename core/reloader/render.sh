#!/usr/bin/env bash
# Renders core/reloader/reloader.yaml from the pinned upstream chart.
#
# Run from anywhere:  ./core/reloader/render.sh
#
# The chart is pulled to a temporary directory before rendering, as in
# core/cert-manager/render.sh: `helm template` against an oci:// chart prints
# "Pulled:" and "Digest:" on STDOUT on a cold cache and would corrupt the file.
set -euo pipefail

CHART="oci://ghcr.io/stakater/charts/reloader"
VERSION="2.2.18"
NAMESPACE="reloader"
RELEASE="reloader"

cd "$(dirname "$0")/../.."
OUT="core/reloader/reloader.yaml"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

DIGEST="$(helm pull "$CHART" --version "$VERSION" --untar --untardir "$TMP" \
  | awk '/^Digest:/ {print $2}')"
[ -n "$DIGEST" ] || { echo "helm pull printed no digest" >&2; exit 1; }

helm template "$RELEASE" "$TMP/reloader" \
  --namespace "$NAMESPACE" \
  --values core/reloader/reloader-values.yaml \
  > "$TMP/rendered.yaml"

{
  echo "# Reloader chart ${VERSION}, rendered from ${CHART}"
  echo "# ${DIGEST}"
  echo "#"
  echo "# Generated by core/reloader/render.sh. Do NOT edit in place —"
  echo "# change core/reloader/reloader-values.yaml and render again."
  cat "$TMP/rendered.yaml"
} > "$OUT"

echo "wrote $OUT"
