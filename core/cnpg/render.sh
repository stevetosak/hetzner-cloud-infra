#!/usr/bin/env bash
# Writes core/cnpg/operator.yaml, plugin-barman-cloud.yaml and crds.yaml from
# the pinned upstream releases.
#
# Run from anywhere:  ./core/cnpg/render.sh
#
# Neither release needs values, so this is not a helm render: it downloads
# the two released manifests, checks each against its pinned sha256, and
# splits them. The CRDs go to crds.yaml, because only kluster applies CRDs
# (ADR 0010, Amendment 2026-10-22). The `cnpg-system` Namespace is cut out of
# the operator, because the seed owns every Namespace; it lives in
# namespace.yaml. Everything else stays the upstream text.
#
# To upgrade: change a version and its sha256 here, run this, and read the
# diff. 🔴 Before upgrading the plugin, read the README on barman and the
# bucket lock.
set -euo pipefail

CNPG_VERSION="1.30.0"
CNPG_URL="https://raw.githubusercontent.com/cloudnative-pg/cloudnative-pg/release-1.30/releases/cnpg-${CNPG_VERSION}.yaml"
CNPG_SHA256="f8bede43fe4ee0d478c2355b204a36876b2ae4faac60f2a9452280b293da3b88"

PLUGIN_VERSION="v0.15.1"
PLUGIN_URL="https://github.com/cloudnative-pg/plugin-barman-cloud/releases/download/${PLUGIN_VERSION}/manifest.yaml"
PLUGIN_SHA256="8f377ff4a7d0d3f74fc64b0f7ac4f449fc38ca9e83a40107cca2f9315a9bd920"

cd "$(dirname "$0")/../.."

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

fetch() { # url sha256 out
  curl -fsSL -o "$3" "$1"
  echo "$2  $3" | sha256sum --check --quiet - \
    || { echo "sha256 mismatch for $1" >&2; exit 1; }
}

fetch "$CNPG_URL" "$CNPG_SHA256" "$TMP/cnpg.yaml"
fetch "$PLUGIN_URL" "$PLUGIN_SHA256" "$TMP/plugin.yaml"

python3 core/split-crds.py "$TMP/cnpg-crds.yaml" --drop-namespace cnpg-system \
  < "$TMP/cnpg.yaml" > "$TMP/cnpg-rest.yaml"
python3 core/split-crds.py "$TMP/plugin-crds.yaml" \
  < "$TMP/plugin.yaml" > "$TMP/plugin-rest.yaml"

{
  echo "# CloudNativePG operator ${CNPG_VERSION}, from ${CNPG_URL}"
  echo "# sha256 ${CNPG_SHA256} (the download, before the split)"
  echo "#"
  echo "# Generated by core/cnpg/render.sh. Do NOT edit in place. The CRDs are in"
  echo "# crds.yaml and the cnpg-system Namespace is in namespace.yaml."
  cat "$TMP/cnpg-rest.yaml"
} > core/cnpg/operator.yaml

{
  echo "# barman-cloud CNPG-I plugin ${PLUGIN_VERSION}, from ${PLUGIN_URL}"
  echo "# sha256 ${PLUGIN_SHA256} (the download, before the split)"
  echo "#"
  echo "# Generated by core/cnpg/render.sh. Do NOT edit in place. The CRD is in"
  echo "# crds.yaml."
  cat "$TMP/plugin-rest.yaml"
} > core/cnpg/plugin-barman-cloud.yaml

{
  echo "# CustomResourceDefinitions of the CloudNativePG operator ${CNPG_VERSION}"
  echo "# and the barman-cloud plugin ${PLUGIN_VERSION}, split by core/cnpg/render.sh."
  echo "# Do NOT edit in place."
  echo "#"
  echo "# Applied by the kluster seed with --server-side, never by ArgoCD: the core"
  echo "# AppProject does not admit CRDs. Not listed in kustomization.yaml."
  cat "$TMP/cnpg-crds.yaml"
  echo "---"
  cat "$TMP/plugin-crds.yaml"
} > core/cnpg/crds.yaml

echo "wrote core/cnpg/operator.yaml, plugin-barman-cloud.yaml and crds.yaml"
